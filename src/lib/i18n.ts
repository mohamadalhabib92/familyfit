const TABLES: Record<Locale, Record<CopyKey, string>> = { fr: FR, en: EN, de: DE, ar: AR };

export function normalizeLocale(value: unknown): Locale {
  if (value === 'en' || value === 'de' || value === 'ar' || value === 'fr') return value;
  return 'fr';
}

export function translate(locale: Locale, key: CopyKey): string {
  return TABLES[locale][key] ?? FR[key];
}
